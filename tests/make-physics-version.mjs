// Generates independent PHYSICS and reference DRIVER identities in src/app/physics-version.js.
// PHYSICS is the SHA-256 of runSource() in tests/load-core.mjs (core/, dynamics/, solver/solver.js;
// drivers are hashed separately; not the presets, which a run file doesn't use). Run files (src/app/runfile.js) carry it, so `git log -S <hash>` finds the
// commit that produced an export. Commit the result with any change to the hashed files. golden.json's older
// meta.sourceSha256 is a different hash (coreSource(), presets included) and is not touched.
//
//   node tests/make-physics-version.mjs           print the hash and whether the committed file is current
//   node tests/make-physics-version.mjs --write   ...and rewrite src/app/physics-version.js
import { writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { runSource, driverSource } from './load-core.mjs';
import { referenceDriver } from '../src/drivers/index.js';

export const PHYSICS_VERSION_PATH = fileURLToPath(new URL('../src/app/physics-version.js', import.meta.url));

export function physicsVersionText() {
  const { files, sha256 } = runSource();
  const driver = driverSource();
  return '// Generated by tests/make-physics-version.mjs --write; do not edit. Hash of the physics source files below,\n' +
    '// computed by runSource() and driverSource() in tests/load-core.mjs. This file is outside both hashed sets.\n' +
    `export const PHYSICS = ${JSON.stringify({ sha256, files }, null, 2)};\n` +
    `export const DRIVER = ${JSON.stringify({ name: referenceDriver.name, sha256: driver.sha256, files: driver.files }, null, 2)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = physicsVersionText();
  let current = null;
  try { current = readFileSync(PHYSICS_VERSION_PATH, 'utf8'); } catch (e) { if (e.code !== 'ENOENT') throw e; }
  console.log(`physics sha256 ${runSource().sha256}\ndriver sha256 ${driverSource().sha256}\ncommitted file is ${current === text ? 'current' : current === null ? 'missing' : 'STALE'}`);
  if (process.argv.includes('--write')) { writeFileSync(PHYSICS_VERSION_PATH, text); console.log(`wrote ${PHYSICS_VERSION_PATH}`); }
}
